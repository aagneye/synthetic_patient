#!/usr/bin/env python
"""Fetch and freeze every external reference this dataset depends on.

SYNTHETIC. In silico cohort validation. Not clinical evidence.

Usage::

    python fetch_reference.py [--offline] [--reference-dir ../reference]

Writes ``reference/variant_catalog.csv``, the frozen CPIC tables, and
``reference/frequency_sources.json``.  Raw API payloads are cached under
``reference/raw/`` so that later runs are reproducible and offline-capable.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from synthpgx.catalog import (  # noqa: E402
    SAS_OVERRIDE_MIN_MAF,
    build_catalog,
    write_reference,
)
from synthpgx.sources import Fetcher  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    here = Path(__file__).resolve().parent
    parser.add_argument("--reference-dir", default=str(here.parent / "reference"))
    parser.add_argument("--qc-dir", default=str(here.parent / "qc"))
    parser.add_argument(
        "--offline",
        action="store_true",
        help="Use only the cached payloads under reference/raw/.",
    )
    args = parser.parse_args()

    reference_dir = Path(args.reference_dir)
    qc_dir = Path(args.qc_dir)
    qc_dir.mkdir(parents=True, exist_ok=True)

    fetcher = Fetcher(reference_dir / "raw", offline=args.offline)
    print("Fetching CPIC / gnomAD / Ensembl / PubMed records ...", flush=True)
    build = build_catalog(fetcher)
    write_reference(build, reference_dir)

    print(f"  variants in catalog : {len(build.variants)}")
    print(f"  CPIC alleles        : {len(build.alleles)}")
    print(f"  CPIC diplotypes     : {len(build.diplotypes)}")
    print(f"  CPIC recommendations: {len(build.recommendations)}")
    print(f"  PMIDs verified      : {len(build.pmids)}")
    print(f"  HTTP cache          : {fetcher.stats}")

    eligible = [v for v in build.variants if v["sas_override_eligible"]]
    print(f"  SAS-override eligible variants: {len(eligible)}")
    for variant in eligible:
        print(f"    {variant['variant_id']:16s} {variant['hgvs_p']:10s} "
              f"{variant['rsid']:14s} {variant['sas_override_reason']}")

    write_open_questions(build, qc_dir / "open_questions.md")
    print(f"  open questions      : {len(build.open_questions)} "
          f"-> {qc_dir / 'open_questions.md'}")
    return 0


def write_open_questions(build, path: Path) -> None:
    lines = [
        "# Open questions and unsourced values",
        "",
        "**SYNTHETIC. In silico cohort validation. Not clinical evidence.**",
        "",
        "Generated by `fetch_reference.py`. Every item here is a value this build "
        "could not source, or a discrepancy between two sources. Nothing listed "
        "here was guessed or filled in; the corresponding fields are null.",
        "",
        "## Resolved during this build",
        "",
        "These were open questions in the build brief that the fetched sources "
        "answered outright.",
        "",
    ]

    resolved = _resolved_notes(build)
    for note in resolved:
        lines.append(f"- {note}")
    lines += ["", "## Still open", ""]

    if not build.open_questions:
        lines.append("- None.")
    for note in sorted(set(build.open_questions)):
        lines.append(f"- {note}")

    lines += [
        "",
        "## Carried over from the build brief (team decisions, not data gaps)",
        "",
        "- Whether `anukriti-pgx-core` v0.5.0 already encodes the Naushad variants "
        "as SAS-override rules. This build computes the override from the spec 4.7 "
        "rule over sourced frequencies, with the MAF threshold ratified at 5 "
        "percent (see `SAS_OVERRIDE_MIN_MAF` in `synthpgx/catalog.py`). If the "
        "engine encodes a different threshold, the engine wins and "
        "`expected_engine_output` must be regenerated.",
        "- Exact threshold values for each R/V/U refusal rule. This build reads the "
        "rule IDs from an `anukriti-swarm` checkout when one is supplied via "
        "`--swarm-source`; without it, refusal rows carry a null "
        "`refusal_rule_id_expected` and are labelled by category instead.",
        "- Public release and licence choice.",
        "- Signatory for GenomeIndia / IndiGen data-access applications.",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _resolved_notes(build) -> list[str]:
    notes: list[str] = []
    by_protein = {
        (v.get("hgvs_p") or "").replace("p.", ""): v for v in build.variants
    }
    for protein in ("V732I", "S534N", "C29R", "I543V", "M166V"):
        variant = by_protein.get(protein)
        if variant:
            notes.append(
                f"`{protein}` = `{variant['variant_id']}` = **{variant['rsid']}** "
                f"at GRCh38 chr1:{variant['grch38_pos']} "
                f"({variant['ref']}>{variant['alt']}), per the CPIC "
                "`sequence_location` table."
            )
    v732 = by_protein.get("V732I")
    c29r = by_protein.get("C29R")
    if v732 and c29r:
        notes.append(
            f"**The internal reference listing V732I as rs1801265 is wrong.** "
            f"V732I is {v732['rsid']}; {c29r['rsid']} is C29R "
            f"({c29r['variant_id']}). Confirmed independently by CPIC "
            "`sequence_location` and the Ensembl variant recoder."
        )
    m166 = by_protein.get("M166V")
    if m166 and m166["rsid"] == "rs2297595":
        notes.append(
            "`M166V` (Naushad 2021) and `rs2297595 / c.496A>G` (Hariprakash 2018) "
            "are the **same variant**, not two. The build brief lists them as "
            "separate catalog entries."
        )
    # Which of the brief's candidate override variants the rule actually admits.
    for protein in ("V732I", "S534N"):
        variant = by_protein.get(protein)
        if not variant:
            continue
        maf = variant.get("freq_gnomad_sas")
        if variant.get("sas_override_eligible"):
            notes.append(
                f"`{protein}` **is** SAS-override eligible: gnomAD SAS MAF "
                f"{maf * 100:.2f}% clears the 5% threshold, Naushad 2021 reports "
                f"a toxicity association in n=2000, and CPIC assigns it "
                f"'{variant.get('cpic_function')}'."
            )
        elif maf is not None and maf <= SAS_OVERRIDE_MIN_MAF:
            notes.append(
                f"**`{protein}` is NOT SAS-override eligible**, and this is a "
                f"settled decision, not an open question. Its gnomAD SAS minor "
                f"allele frequency is {maf * 100:.2f}%, below the "
                f"{SAS_OVERRIDE_MIN_MAF * 100:.0f}% threshold. The build brief "
                "treats it alongside V732I as a driver of the override; the "
                "team ratified the threshold as written and excluded "
                f"{protein}. Naushad 2021 reports its toxicity association but "
                "quotes no Indian allele frequency for it, so there is no "
                "sourced figure that would place it above the line. Only V732I "
                "qualifies."
            )

    naushad = build.pmids.get("33105068")
    if naushad:
        notes.append(
            f"PMID 33105068 first author is **{naushad['first_author']}** "
            f"({naushad['journal']}, {naushad['pubdate']}), confirming the "
            "Naushad attribution rather than Jain."
        )
    hari = build.pmids.get("29239269")
    if hari:
        notes.append(
            "PMID 29239269 (Hariprakash et al. 2018) has V. Scaria as senior "
            "author, so the brief's 'Scaria et al. set of 25 novel Indian DPYD "
            "variants' most likely refers to this same paper. No separate file "
            "`scaria_dpyd_novel_variants.csv` exists in this repository, and "
            "none of its 25 variants were invented."
        )
    return notes


if __name__ == "__main__":
    raise SystemExit(main())
